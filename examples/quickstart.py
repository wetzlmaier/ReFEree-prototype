"""
Quickstart Example for ReFEree.

Demonstrates evaluating a code snippet and its summary using ReFEree.
"""

import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from referee import ReFEreeEvaluator, MockLLMClient

# 1. Target function code to evaluate
code = '''
def calculate_discount(price: float, discount_percent: float) -> float:
    """Calculates discounted price given original price and percentage."""
    if discount_percent < 0 or discount_percent > 100:
        raise ValueError("Invalid discount percentage")
    discount_amount = price * (discount_percent / 100.0)
    return round(price - discount_amount, 2)
'''

# 2. Candidate summary generated by an LLM
# Note: Sentence 2 claims it returns an integer instead of a float (Type Inconsistency C2)
# and sentence 3 mentions database storage which is irrelevant (Context Irrelevant C4)
summary = (
    "The calculate_discount function calculates the final discounted price from an original price. "
    "It validates the discount percentage and returns the discounted price as an integer. "
    "This method is commonly deployed alongside relational database triggers to synchronize invoices."
)


def main():
    print("Evaluating Code Summary using ReFEree...")

    # We use MockLLMClient for demonstration without requiring an OpenAI API key.
    # To use OpenAI models (e.g. gpt-4.1-mini as in paper):
    # evaluator = ReFEreeEvaluator(llm_client=OpenAILLMClient(model="gpt-4.1-mini"))
    mock_client = MockLLMClient(default_score=1)
    # Sentence 2 has type inconsistency (C2)
    mock_client.set_rule("returns the discounted price as an integer", "type", 0)
    # Sentence 3 has irrelevant context (C4)
    mock_client.set_rule("database triggers", "context", 0)

    evaluator = ReFEreeEvaluator(llm_client=mock_client)
    result = evaluator.evaluate(input_code=code, summary=summary)

    print(result.summary_report())


if __name__ == "__main__":
    main()
